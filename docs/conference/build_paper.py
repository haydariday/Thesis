"""Combine the chapter sources into conference.tex (title, ToC, chapters, IEEE references) and build the PDF.

Usage (from any directory):
    python3 docs/conference/build_paper.py           # conference.tex + conference.pdf
    python3 docs/conference/build_paper.py --tex-only

conference.tex is generated. Edit the chapter .src.md files, then rerun this script.
The PDF needs pdflatex and biber (Arch: texlive-basic texlive-latex texlive-latexrecommended
texlive-latexextra texlive-fontsrecommended texlive-bibtexextra biber).
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Chapter versions that go into the paper. Bump these when a new version folder is made.
CHAPTERS = [
    HERE / "sub/chapter 1/v2/chapter-1.src.md",
    HERE / "sub/chapter 2/v1/chapter-2.src.md",
]

TITLE = ("Persona-Based Multi-Agent LLM Debate as an Automated Playtester: "
         "Validating Game Difficulty Data Against Human Performance Baselines")
AUTHOR = r"Muhammad Haydar Maulana\\[0.3em] \normalsize Master of Informatics\\ \normalsize\texttt{haydariday@gmail.com}"
DATE = "October 2026"

PREAMBLE = r"""%% GENERATED by build_paper.py from the chapter .src.md files. Do not edit by hand.
\documentclass[12pt,a4paper]{report}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{mathptmx}
\usepackage[margin=2.5cm]{geometry}
\usepackage{setspace}
\onehalfspacing
\usepackage{csquotes}
\usepackage[style=ieee,backend=biber]{biblatex}
\addbibresource{references.bib}
\usepackage{titlesec}
\titleformat{\chapter}[display]{\normalfont\large\bfseries\centering}{CHAPTER \thechapter}{0.3em}{\MakeUppercase}
\titlespacing*{\chapter}{0pt}{0pt}{1.5em}
\usepackage[hidelinks]{hyperref}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
"""


def chapter_markdown(path):
    text = path.read_text(encoding="utf-8")
    text = text[: text.index("## References")].rstrip() + "\n"
    lines = text.splitlines()
    # "# CHAPTER 1 INTRODUCTION" -> "# Introduction"; numbering comes from LaTeX.
    m = re.match(r"#\s+CHAPTER\s+\S+\s+(.+)", lines[0])
    if not m:
        sys.exit(f"{path}: first line must be '# CHAPTER <n> <TITLE>'")
    lines[0] = "# " + m.group(1).title()
    text = "\n".join(lines)
    return re.sub(r"^(#{2,})\s+\d+(?:\.\d+)*\s+", r"\1 ", text, flags=re.M)


def main():
    combined = "\n\n".join(chapter_markdown(p) for p in CHAPTERS)
    body = subprocess.run(
        ["pandoc", "-f", "markdown", "-t", "latex", "--biblatex", "--top-level-division=chapter"],
        input=combined, capture_output=True, text=True, check=True,
    ).stdout
    tex = (PREAMBLE
           + f"\n\\title{{\\textbf{{{TITLE}}}}}\n\\author{{{AUTHOR}}}\n\\date{{{DATE}}}\n\n"
           + "\\begin{document}\n\\maketitle\n\\tableofcontents\n\n"
           + body
           + "\n\\printbibliography[heading=bibintoc,title={References}]\n\\end{document}\n")
    out = HERE / "conference.tex"
    out.write_text(tex, encoding="utf-8")
    print(f"wrote {out.relative_to(HERE.parent.parent)}")

    if "--tex-only" in sys.argv:
        return
    missing = [t for t in ("pdflatex", "biber") if not shutil.which(t)]
    if missing:
        sys.exit(f"skipping PDF: {', '.join(missing)} not installed")
    build = HERE / "build"
    build.mkdir(exist_ok=True)
    latex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", f"-output-directory={build}", "conference.tex"]
    steps = [latex, ["biber", f"--input-directory={HERE}", f"--output-directory={build}", "conference"], latex, latex]
    for cmd in steps:
        r = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"{cmd[0]} failed:\n{r.stdout[-3000:]}{r.stderr[-1000:]}")
    shutil.copy(build / "conference.pdf", HERE / "conference.pdf")
    print("wrote docs/conference/conference.pdf")


if __name__ == "__main__":
    main()
